/* ── Live Browser View Types ── */

export interface LiveBrowserStep {
  stepIndex: number;
  action: string;
  actionDetail: string;
  url: string;
  success?: boolean;
  durationMs?: number;
}

export type QuickUseStreamEvent =
  | {
      type: "meta";
      meta: {
        estimatedCredits?: number;
        executionId?: string;
        taskId?: string;
      };
    }
  | {
      type: "progress";
      message: string;
      detail?: string;
    }
  | {
      type: "finding";
      message: string;
    }
  | {
      type: "swarm_event";
      event: SwarmEvent;
    }
  | {
      type: "memory";
      memories: QuickUseMemoryPreview[];
      autoApplied?: boolean;
    }
  | {
      type: "result";
      result: QuickUseResult;
      credits?: QuickUseCreditInfo;
    }
  | {
      type: "error";
      error: string;
      suggestions?: string[];
    }
  | {
      type: "intervention_ack";
      interventionId: string;
      message: string;
    }
  | {
      /** Browser navigated to a new URL */
      type: "browser_navigation";
      url: string;
      stepIndex: number;
    }
  | {
      /** Live screenshot from browser (JPEG, max ~100KB) */
      type: "browser_screenshot";
      /** Base64 JPEG data (no data URL prefix) */
      imageData: string;
      stepIndex: number;
      url: string;
    }
  | {
      /** Agent performed an action */
      type: "browser_action";
      step: LiveBrowserStep;
    }
  | {
      /** Agent's current reasoning/thinking */
      type: "browser_thinking";
      thought: string;
      stepIndex: number;
    }
  | {
      /** A step completed */
      type: "browser_step_complete";
      stepIndex: number;
      action: string;
      success: boolean;
    };
